#!/usr/bin/env python3
"""Regenerate rules/popular_packages.tsv: the most-downloaded npm and PyPI
packages, the names typo-squats and look-alikes copy (cve.rs). Regenerate
now and then so new popular packages are covered:

  python3 rules/gen_popular_packages.py > rules/popular_packages.tsv
"""

import json
import sys
import urllib.request

API = "https://packages.ecosyste.ms/api/v1/registries/{}/packages?sort=downloads&order=desc&per_page=100&page={}"
REGISTRIES = {"npm": "npmjs.org", "PyPI": "pypi.org"}
PAGES = 10


def page(registry, n):
    req = urllib.request.Request(API.format(registry, n), headers={"User-Agent": "kalascan-rules"})
    with urllib.request.urlopen(req, timeout=90) as r:
        return json.load(r)


def main():
    print(f"# Generated by rules/gen_popular_packages.py: the top {PAGES * 100} npm and PyPI packages by downloads (ecosyste.ms).")
    print("# ecosystem<TAB>name")
    for eco, registry in REGISTRIES.items():
        seen = set()
        for n in range(1, PAGES + 1):
            for row in page(registry, n):
                name = row["name"].lower()
                if name not in seen:
                    seen.add(name)
                    print(f"{eco}\t{name}")
        print(f"{eco}: {len(seen)} names", file=sys.stderr)


main()
