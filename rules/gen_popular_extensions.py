#!/usr/bin/env python3
"""Regenerate rules/popular_extensions.tsv: the most-installed VS Code
extensions and the source repository each one declares.

A copy of a popular extension republished under another publisher keeps the
original's `repository` field; reputation.rs flags that. Regenerate now and
then so new popular extensions are covered:

  python3 rules/gen_popular_extensions.py > rules/popular_extensions.tsv
"""

import json
import re
import sys
import urllib.request

API = "https://marketplace.visualstudio.com/_apis/public/gallery/extensionquery"
PAGES, PAGE_SIZE = 2, 1000
# IncludeFiles | IncludeVersionProperties | IncludeStatistics | IncludeLatestVersionOnly
FLAGS = 0x2 | 0x10 | 0x100 | 0x200


def normalize(url):
    """`git+https://github.com/Foo/bar.git#main` -> `github.com/foo/bar`."""
    m = re.search(r"(github\.com|gitlab\.com|bitbucket\.org)[/:]([\w.-]+)/([\w.-]+)", url or "", re.I)
    if not m:
        return None
    repo = re.sub(r"\.git$", "", m.group(3))
    return f"{m.group(1)}/{m.group(2)}/{repo}".lower()


def page(n):
    body = {
        "filters": [{
            "criteria": [{"filterType": 8, "value": "Microsoft.VisualStudio.Code"}],
            "pageNumber": n, "pageSize": PAGE_SIZE, "sortBy": 4, "sortOrder": 0,
        }],
        "flags": FLAGS,
    }
    req = urllib.request.Request(API, json.dumps(body).encode(), {
        "Content-Type": "application/json",
        "Accept": "application/json;api-version=7.2-preview.1",
    })
    return json.load(urllib.request.urlopen(req, timeout=60))["results"][0]["extensions"]


rows = set()
for n in range(1, PAGES + 1):
    for e in page(n):
        props = {p["key"]: p["value"] for p in e["versions"][0].get("properties", [])}
        repo = normalize(props.get("Microsoft.VisualStudio.Services.Links.Source")
                         or props.get("Microsoft.VisualStudio.Services.Links.GitHub"))
        if repo:
            rows.add((repo, f'{e["publisher"]["publisherName"]}.{e["extensionName"]}'.lower()))

print(f"# Generated by rules/gen_popular_extensions.py from the top {PAGES * PAGE_SIZE} VS Code Marketplace extensions by installs.")
print("# repository<TAB>publisher.name")
for repo, ext in sorted(rows):
    print(f"{repo}\t{ext}")
print(f"{len(rows)} rows", file=sys.stderr)
